def _env_bool(name: str, default: bool) -> bool:
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in {'1', 'true', 'yes', 'on'}


def _env_int(name: str, default: int, *, minimum: int | None = None) -> int:
    raw = os.environ.get(name)
    if raw in (None, ''):
        value = default
    else:
        try:
            value = int(raw)
        except ValueError:
            value = default
    if minimum is not None:
        value = max(value, minimum)
    return value


def _psycopg_pool_options() -> dict | None:
    if not _env_bool('DB_POOL_ENABLED', True):
        return None

    min_size = _env_int('DB_POOL_MIN_SIZE', 4, minimum=1)
    # Default 40 (was 20): slow image-gen / OpenAI requests each hold a pooled
    # connection for their whole duration, so 20 exhausted under load → PoolTimeout.
    # Postgres allows 300 (db service), and min_size stays 4 so idle footprint is
    # unchanged — only services under real concurrency (the API) grow toward 40.
    max_size = _env_int('DB_POOL_MAX_SIZE', 40, minimum=1)
    if max_size < min_size:
        raise ImproperlyConfigured('DB_POOL_MAX_SIZE must be greater than or equal to DB_POOL_MIN_SIZE')
    max_waiting_default = max_size * 3

    return {
        'min_size': min_size,
        'max_size': max_size,
        'timeout': _env_int('DB_POOL_TIMEOUT', 15, minimum=1),
        'max_waiting': _env_int('DB_POOL_MAX_WAITING', max_waiting_default, minimum=1),
        'max_lifetime': _env_int('DB_POOL_MAX_LIFETIME', 600, minimum=60),  # recycle old connections
        'max_idle': _env_int('DB_POOL_MAX_IDLE', 300, minimum=30),  # close long-idle pooled connections
    }


