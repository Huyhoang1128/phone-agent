SIMPLE_JWT = {
    # Short access lifetime bounds the window where a revoked session can still
    # act on services that only verify the JWT signature (e.g. agent-teams),
    # since instant revocation (token_version) is enforced on Django + refresh.
    'ACCESS_TOKEN_LIFETIME': timedelta(minutes=15),
    'REFRESH_TOKEN_LIFETIME': timedelta(days=30),
    # No rotation/blacklist: revocation is handled by token_version. Rotation +
    # BLACKLIST_AFTER_ROTATION would blacklist the old refresh on first use, so
    # concurrent refreshes (a dashboard firing many requests at once when the
    # access token expires) race — the losers hit a blacklisted token and get
    # logged out. Keeping the refresh token stable avoids that.
    'ROTATE_REFRESH_TOKENS': False,
}

