def _parse_tenant_keys(raw, label):
    """'slugA:key1,slugB:key2' → {'slugA': 'key1', 'slugB': 'key2'}.

    Một biến môi trường duy nhất chứa key của MỌI công ty, thay vì một biến cho mỗi
    công ty: docker-compose ở project này liệt kê từng biến một trong khối
    ``environment:`` (không dùng ``env_file``), nên mỗi biến mới lại phải sửa compose
    — đúng cái bẫy đã làm UPSCALE_API_URL không tới được container. Với cách này,
    thêm công ty thứ ba chỉ cần sửa .env, compose không đụng tới.

    Key của OpenAI/fal không chứa dấu ',' hay ':' nên tách bằng chúng là an toàn;
    ``split(':', 1)`` để key có ':' vẫn nguyên vẹn. Dòng sai cú pháp bị bỏ qua kèm
    cảnh báo chứ không làm sập server lúc khởi động.
    """
    out = {}
    for chunk in (raw or '').split(','):
        chunk = chunk.strip()
        if not chunk:
            continue
        if ':' not in chunk:
            print(f'[settings] {label}: bỏ qua mục sai cú pháp (thiếu dấu ":"): {chunk[:24]}…')
            continue
        slug, _, key = chunk.partition(':')
        slug, key = slug.strip(), key.strip()
        if not slug or not key:
            print(f'[settings] {label}: bỏ qua mục thiếu slug hoặc key: {chunk[:24]}…')
            continue
        out[slug] = key
    return out


