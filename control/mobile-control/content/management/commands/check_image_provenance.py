"""Single-image provenance survival check (audit instrument).

Port of ``bybass/provenance-audit/check_image.py`` into a Django management
command so it runs inside the backend container with the same Pillow build the
upload path uses. It is dependency-light: detection is a raw-byte scan (no
``exiftool`` / ``c2pa`` SDK required).

Workflow it supports for a platform-survival study:

  1. Bring (or download) an image — e.g. one generated by an AI tool that
     embeds a C2PA / IPTC marker, or one already served back by a platform.
  2. Inspect which container-level provenance markers it carries.
  3. Optionally produce a NEW image from it via a chosen re-encode method.
  4. Re-inspect the new image and print a before/after verdict, i.e. whether
     the marker SURVIVED or was STRIPPED by the transform.

What this can and cannot see (read before interpreting):
  * It inspects CONTAINER-LEVEL provenance only — XMP / IPTC ``DigitalSourceType``
    and an embedded C2PA / JUMBF manifest.
  * It CANNOT detect invisible PIXEL watermarks (e.g. Google SynthID) or a
    platform's server-side ML classifier.
  Therefore "no marker found locally" is necessary but NOT sufficient evidence
  that a platform would fail to flag the image. Confirm with an actual,
  ethically-run upload test. Do not over-claim.

Examples::

    # Just inspect a local file or a URL the platform served back
    python manage.py check_image_provenance ./work/openai_out.png
    python manage.py check_image_provenance https://cdn.example/served.jpg

    # Inspect, then strip via a Pillow JPEG re-encode and show the verdict
    python manage.py check_image_provenance ./openai_out.png \
        --sanitize --fmt JPEG --quality 85 --out ./stripped.jpg
"""
from __future__ import annotations

from pathlib import Path

import requests
from django.core.management.base import BaseCommand, CommandError

from content.image_utils import detect_provenance, format_meta, sanitize_image

_TIMEOUT = 30


def _load_bytes(target: str) -> bytes:
    """Return raw bytes for ``target``, which may be a URL or a local path."""
    if target.startswith(('http://', 'https://')):
        resp = requests.get(target, timeout=_TIMEOUT)
        resp.raise_for_status()
        return resp.content
    path = Path(target)
    if not path.is_file():
        raise CommandError(f'Not a URL and not an existing file: {target}')
    return path.read_bytes()


def _verdict(before: bool, after: bool) -> str:
    if not before:
        return '—  (absent)'
    return 'SURVIVED' if after else 'STRIPPED'


class Command(BaseCommand):
    help = 'Inspect (and optionally strip) container-level AI-provenance markers in an image.'

    def add_arguments(self, parser):
        parser.add_argument('target', help='Local file path or http(s) URL of the image.')
        parser.add_argument(
            '--sanitize',
            action='store_true',
            help='Re-encode the image (strip metadata) and print a before/after verdict.',
        )
        parser.add_argument('--fmt', default='JPEG', help='Sanitize output format (JPEG/PNG/WEBP).')
        parser.add_argument('--quality', type=int, default=95, help='JPEG/WEBP quality (default 95).')
        parser.add_argument(
            '--max-edge',
            type=int,
            default=None,
            help='Downscale longest side to this many px before re-encoding.',
        )
        parser.add_argument(
            '--out',
            default=None,
            help='Write the sanitized image to this path (implies --sanitize).',
        )

    def _report(self, label: str, flags: dict) -> None:
        self.stdout.write(f'  {label}:')
        self.stdout.write(f'    XMP/IPTC DigitalSourceType (AI) : {"yes" if flags["xmp_ai"] else "no"}')
        self.stdout.write(f'    C2PA manifest present          : {"yes" if flags["c2pa"] else "no"}')
        self.stdout.write(f'    EXIF block present             : {"yes" if flags["exif"] else "no"}')

    def handle(self, *args, **opts):
        target = opts['target']
        do_sanitize = opts['sanitize'] or bool(opts['out'])

        try:
            raw = _load_bytes(target)
        except (requests.RequestException, CommandError) as exc:
            raise CommandError(f'Could not load image: {exc}') from exc

        self.stdout.write(self.style.MIGRATE_HEADING(f'Provenance check: {target}  ({len(raw)} bytes)'))
        before = detect_provenance(raw)
        self._report('before', before)

        if not do_sanitize:
            if not before['any']:
                self.stdout.write(self.style.WARNING(
                    '  No container-level markers found. NOTE: pixel watermarks / '
                    'server-side classifiers are NOT covered by this check.'))
            return

        try:
            stripped = sanitize_image(
                raw,
                fmt=opts['fmt'],
                quality=opts['quality'],
                max_edge=opts['max_edge'],
            )
        except Exception as exc:
            raise CommandError(f'Sanitize failed: {exc}') from exc

        after = detect_provenance(stripped)
        self.stdout.write(self.style.MIGRATE_HEADING(
            f'After {opts["fmt"]} re-encode (q={opts["quality"]}, '
            f'max_edge={opts["max_edge"]})  ({len(stripped)} bytes)'))
        self._report('after', after)

        self.stdout.write(self.style.MIGRATE_HEADING('Verdict (marker survival)'))
        self.stdout.write(f'    XMP/IPTC : {_verdict(before["xmp_ai"], after["xmp_ai"])}')
        self.stdout.write(f'    C2PA     : {_verdict(before["c2pa"], after["c2pa"])}')
        self.stdout.write(f'    EXIF     : {_verdict(before["exif"], after["exif"])}')

        if opts['out']:
            _, ext = format_meta(opts['fmt'])
            out_path = Path(opts['out'])
            out_path.write_bytes(stripped)
            self.stdout.write(self.style.SUCCESS(f'  Wrote sanitized image → {out_path} (.{ext})'))
