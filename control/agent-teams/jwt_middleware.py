"""
JWT Middleware for AgentOS
==========================

This middleware validates JWT tokens generated by Django (rest_framework_simplejwt)
and injects user_id, session_id, and custom claims into AgentOS endpoints.

The middleware is compatible with Django SimpleJWT which uses:
- HS256 signing algorithm
- Secret key: DJANGO_SECRET_KEY environment variable
- Claims: user_id (int), standard JWT claims
"""

import logging
import os
from typing import Dict, List, Optional, Any
from datetime import datetime

import jwt
from fastapi import Request, HTTPException
from fastapi.security import HTTPBearer, HTTPAuthorizationCredentials
# from starlette.middleware.base import BaseHTTPMiddleware
from agno.os.middleware import JWTMiddleware
from starlette.responses import JSONResponse

# Secret key shared with Django (rest_framework_simplejwt uses DJANGO_SECRET_KEY with HS256)
DJANGO_JWT_SECRET_KEY = os.getenv(
    "DJANGO_SECRET_KEY",
    "django-insecure-change-me-in-production",
)


class GoJWTBearer(HTTPBearer):
    """HTTP Bearer authentication for Go JWT tokens"""
    
    def __init__(self, auto_error: bool = True):
        super().__init__(auto_error=auto_error)
    
    async def __call__(self, request: Request) -> Optional[HTTPAuthorizationCredentials]:
        credentials = await super().__call__(request)
        if credentials:
            if credentials.scheme != "Bearer":
                raise HTTPException(
                    status_code=403, 
                    detail="Invalid authentication scheme"
                )
            return credentials
        return None


class GoJWTMiddleware(JWTMiddleware):
    """
    JWT Middleware for validating tokens from Django (rest_framework_simplejwt).

    This middleware overrides parameters from the parent JWTMiddleware to work
    with Django SimpleJWT:
    - Uses HS256 algorithm
    - Uses "user_id" claim (SimpleJWT default)
    - Secret key is read from the DJANGO_SECRET_KEY environment variable
    - Converts numeric user_id to string if needed
    - Properly passes all parameters to parent constructor

    The parent JWTMiddleware handles:
    1. Extracting JWT tokens from Authorization header or cookies
    2. Validating tokens using the configured secret key
    3. Extracting user_id and other claims
    4. RBAC scope checking (if enabled)
    5. Injecting claims into request state for use in endpoints
    6. Handling token validation errors with appropriate HTTP responses
    """
    
    def __init__(
        self,
        app,
        verification_key: Optional[str] = None,
        algorithm: str = "HS256",
        user_id_claim: str = "user_id",
        session_id_claim: str = "session_id",
        dependencies_claims: Optional[List[str]] = None,
        validate: bool = True,
        authorization: bool = False,
        verify_audience: bool = False,
        audience: Optional[str] = None,
        excluded_route_paths: Optional[List[str]] = None,
        token_header_key: str = "Authorization",
        cookie_name: str = "access_token",
        token_source: str = "HEADER",  # HEADER, COOKIE, or BOTH
        # Additional parameters for parent class compatibility
        jwks_file: Optional[str] = None,
        secret_key: Optional[str] = None,  # Deprecated
        scopes_claim: str = "scopes",
        audience_claim: str = "aud",
        session_state_claims: Optional[List[str]] = None,
        scope_mappings: Optional[Dict[str, List[str]]] = None,
        admin_scope: Optional[str] = None,
        # Go-specific parameters
        convert_user_id_to_string: bool = True,
    ):
        # Convert token_source string to TokenSource enum if needed
        # First check if TokenSource is available
        try:
            from agno.os.middleware import TokenSource
            token_source_enum = getattr(TokenSource, token_source.upper(), TokenSource.HEADER)
        except (ImportError, AttributeError):
            # Fallback to string representation
            token_source_enum = token_source
        
        # Convert verification_key to verification_keys list for parent
        verification_keys = []
        if verification_key:
            verification_keys.append(verification_key)
        elif DJANGO_JWT_SECRET_KEY:
            verification_keys.append(DJANGO_JWT_SECRET_KEY)
        
        # Call parent constructor with all parameters
        super().__init__(
            app=app,
            verification_keys=verification_keys,
            jwks_file=jwks_file,
            secret_key=secret_key,
            algorithm=algorithm,
            validate=validate,
            authorization=authorization,
            token_source=token_source_enum,
            token_header_key=token_header_key,
            cookie_name=cookie_name,
            scopes_claim=scopes_claim,
            user_id_claim=user_id_claim,
            session_id_claim=session_id_claim,
            audience_claim=audience_claim,
            audience=audience,
            verify_audience=verify_audience,
            dependencies_claims=dependencies_claims,
            session_state_claims=session_state_claims,
            scope_mappings=scope_mappings,
            excluded_route_paths=excluded_route_paths,
            admin_scope=admin_scope,
        )
        
        # Store configuration for reference
        self.jwt_verification_key = verification_key or DJANGO_JWT_SECRET_KEY
        self.jwt_algorithm = algorithm
        self.jwt_user_id_claim = user_id_claim
        self.jwt_session_id_claim = session_id_claim
        self.convert_user_id_to_string = convert_user_id_to_string
        
        # Security scheme for OpenAPI documentation
        self.security_scheme = GoJWTBearer()
    
    async def dispatch(self, request: Request, call_next):
        """
        Override dispatch to handle JWT token processing.
        Converts numeric user_id to string for consistency.
        """
        # Create a wrapper around call_next to convert user_id before the request is processed
        async def call_next_wrapper(request: Request):
            # Convert user_id to string if needed
            if (hasattr(request.state, 'user_id') and 
                request.state.user_id is not None and
                self.convert_user_id_to_string and
                isinstance(request.state.user_id, (int, float))):
                # Convert numeric user_id to string for compatibility
                # Go system uses uint for user_id, but some Python code might expect string
                original_user_id = request.state.user_id
                request.state.user_id = str(int(original_user_id))
                request.state.original_numeric_user_id = original_user_id

            # When request comes from the internal scheduler the middleware sets
            # user_id to "__scheduler__".  Override it with the actual user_id
            # that the schedule creator stored in the form payload.
            # NOTE: This path is only reachable when the internal service token
            # (a random secret managed by AgentOS) has already been validated by
            # the parent middleware, so the form data is trusted in this context.
            if getattr(request.state, 'user_id', None) == '__scheduler__':
                try:
                    # Cache the raw body first so that downstream handlers can still
                    # read the request body after we inspect it here.  Without this,
                    # Starlette's _CachedRequest.wrapped_receive() would return an
                    # empty body to the endpoint because _stream_consumed would be
                    # True but _body would not be set, causing the 422 "message field
                    # required" error on the /agents/{id}/runs endpoint.
                    await request.body()
                    form_data = await request.form()
                    payload_user_id = form_data.get('user_id')
                    if payload_user_id and str(payload_user_id) != '__scheduler__':
                        request.state.user_id = str(payload_user_id)
                except Exception as exc:
                    logging.getLogger(__name__).warning(
                        f"GoJWTMiddleware: failed to read user_id from scheduler form data: {exc}"
                    )

            # Call the original call_next
            return await call_next(request)
        
        # Let parent handle the main dispatch logic with our wrapper
        response = await super().dispatch(request, call_next_wrapper)
        
        return response
    
    @classmethod
    def create_middleware_config(cls, **kwargs):
        """Helper method to create middleware configuration"""
        return {
            "middleware_class": cls,
            **kwargs
        }
    
    @staticmethod
    def generate_test_token(user_id: int, expires_in_days: int = 30) -> str:
        """
        Generate a test JWT token signed with DJANGO_SECRET_KEY for testing purposes.

        Args:
            user_id: User ID (integer)
            expires_in_days: Token expiration in days (default: 30)

        Returns:
            JWT token string
        """
        import time
        payload = {
            "user_id": user_id,
            "exp": int(time.time()) + (expires_in_days * 24 * 3600),
            "iat": int(time.time()),
        }
        token = jwt.encode(payload, DJANGO_JWT_SECRET_KEY, algorithm="HS256")
        return token


# Convenience function to add middleware to AgentOS app
def add_go_jwt_middleware(app, **kwargs):
    """Add Django-compatible JWT middleware to FastAPI app"""
    middleware = GoJWTMiddleware(app, **kwargs)
    return middleware


